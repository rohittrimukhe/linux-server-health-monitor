"""Format-independent report document built from a run (or a fleet of runs).

Report types:
  executive  - management view: health, key issues, summary tables, trends, recommendations
  technical  - everything above plus every detail table and evidence
  full       - technical plus appendix (module errors, skipped checks, raw evidence)
"""
import os
import time

from lshme import APP_NAME, BRAND_LOGO, COPYRIGHT, VERSION
from lshme.core.model import SEV_RANK, Table
from lshme.core.util import redact

REPORT_TYPES = ("executive", "technical", "full")
SEV_COLORS = {"CRITICAL": "#c62828", "WARNING": "#ef8f00", "UNKNOWN": "#6d6d6d", "INFO": "#1565c0",
              "HEALTHY": "#2e7d32", "OK": "#2e7d32"}


class Section(object):
    def __init__(self, name, title, status, score, summary, findings, tables, notes=None):
        self.name = name
        self.title = title
        self.status = status
        self.score = score
        self.summary = summary
        self.findings = findings
        self.tables = tables
        self.notes = notes or []


class ReportDoc(object):
    def __init__(self):
        self.title = ""
        self.subtitle = ""
        self.report_type = "technical"
        self.kind = "host"  # host | fleet
        self.generated = time.time()
        self.meta = []
        self.health = {}
        self.counts = {}
        self.findings = []
        self.module_rows = []
        self.key_tables = []
        self.sections = []
        self.recommendations = []
        self.appendix = []
        self.charts = {"filesystems": [], "score_history": [], "modules": []}
        self.banner = ""
        self.host = ""
        self.copyright = COPYRIGHT
        self.brand_logo = BRAND_LOGO if os.path.isfile(BRAND_LOGO) else ""
        self.customer_logo = ""

    @property
    def status(self):
        return self.health.get("status", "UNKNOWN")

    @property
    def score(self):
        return self.health.get("score", 0)


def _clean_table(t, max_rows=None):
    rows = [[redact(str(c)) if isinstance(c, str) else c for c in r] for r in t.rows]
    note = t.note
    if max_rows and len(rows) > max_rows:
        note = (note + " " if note else "") + "(%d of %d rows shown)" % (max_rows, len(rows))
        rows = rows[:max_rows]
    return Table(t.title, t.headers, rows, note, t.kind)


def build(run, cfg, report_type="technical"):
    if report_type not in REPORT_TYPES:
        report_type = "technical"
    d = ReportDoc()
    d.report_type = report_type
    d.host = run.host
    meta = run.meta or {}
    d.customer_logo = (cfg.get("main", "general", "logo", "") if cfg else "") or meta.get("logo", "")
    custom_title = cfg.get("reports", "reports", "title", "") if cfg else ""
    d.title = custom_title or "Linux Server Health Report"
    d.subtitle = "%s — %s report" % (run.fqdn or run.host, report_type.capitalize())
    period = "last %d day%s" % (run.days, "s" if run.days != 1 else "")
    d.meta = [(k, v) for k, v in (
        ("Company", meta.get("company")), ("Customer", meta.get("customer")), ("Server", run.fqdn or run.host),
        ("IP address", run.ip), ("Environment", meta.get("environment")), ("Location", meta.get("location")),
        ("Report type", report_type.capitalize()), ("Schedule", run.schedule), ("Report period", period),
        ("Collected", time.strftime("%Y-%m-%d %H:%M:%S %Z", time.localtime(run.collected_at))),
        ("Prepared by", meta.get("prepared_by")), ("Generated by", "%s v%s" % (APP_NAME, run.version or VERSION)),
    ) if v]
    d.health = run.health
    d.counts = run.health.get("counts", run.counts())
    max_ev = cfg.getint("reports", "reports", "max_evidence_chars", 3000) if cfg else 3000
    for f in run.findings("INFO"):
        fd = f.to_dict()
        fd["evidence"] = redact(fd["evidence"])[:max_ev]
        fd["message"] = redact(fd["message"])
        d.findings.append(fd)
    if run.maintenance:
        d.banner = "MAINTENANCE WINDOW ACTIVE until %s (%s) — alerts suppressed" % (
            time.strftime("%Y-%m-%d %H:%M", time.localtime(run.maintenance.get("until", 0))), run.maintenance.get("reason", ""))
    for ms in run.health.get("modules", []):
        m = run.module(ms["module"])
        d.module_rows.append([ms["title"], "" if ms["score"] is None else ms["score"],
                              "SKIPPED" if ms["score"] is None else ({"CRITICAL": "CRITICAL", "WARNING": "WARNING"}.get(ms["worst"], "OK")),
                              ms["critical"], ms["warning"], m.summary if m else ""])
        if ms["score"] is not None:
            d.charts["modules"].append((ms["title"], ms["score"]))
    st = run.module("storage")
    if st:
        for fs in st.data.get("filesystems", [])[:25]:
            d.charts["filesystems"].append((fs["mountpoint"], fs.get("used_percent") or 0))
    d.charts["score_history"] = [(t, s) for t, s in (run.trends or {}).get("score_history", []) if s is not None]

    max_rows = None if report_type != "executive" else 25
    for m in run.modules:
        if m.status == "SKIPPED" and not m.findings and report_type == "executive":
            continue
        tables = [t for t in m.tables if report_type != "executive" or t.kind == "summary"]
        tables = [_clean_table(t, max_rows if report_type == "executive" else 2000) for t in tables if t.rows]
        notes = []
        if m.skipped:
            notes.append("Not checked: " + "; ".join(m.skipped))
        if m.errors and report_type != "executive":
            notes.append("Errors: " + "; ".join(e.splitlines()[-1] for e in m.errors))
        fl = [f for f in d.findings if f["module"] == m.name]
        d.sections.append(Section(m.name, m.title, m.status, m.score, m.summary, fl, tables, notes))
        if m.name in ("system", "cpu_memory", "storage"):
            d.key_tables.extend(t for t in tables if t.kind == "summary")
    if getattr(run, "excluded", None):
        rows = [[x["severity"], x["component"], x["message"], x["rule"], x["reason"], x.get("owner", ""), x["until"]] for x in run.excluded]
        d.sections.append(Section("excluded", "Excluded findings (accepted exceptions)", "OK", None,
                                  "%d finding(s) excluded by rules in exclusions.conf; they do not affect the score or alerts." % len(rows), [],
                                  [Table("Excluded findings", ["Severity", "Component", "Finding", "Rule", "Reason", "Owner", "Until"], rows, kind="summary")]))
    seen = set()
    for f in d.findings:
        if SEV_RANK[f["severity"]] >= 2 and f["recommendation"] and f["recommendation"] not in seen:
            seen.add(f["recommendation"])
            d.recommendations.append((f["severity"], f["component"], f["recommendation"]))
    if report_type == "full":
        for m in run.modules:
            if m.errors:
                d.appendix.append(("Module errors: %s" % m.title, "\n\n".join(m.errors)))
            evid = ["[%s] %s %s\n%s" % (f.severity, f.code, f.component, redact(f.evidence)) for f in m.findings if f.evidence]
            if evid:
                d.appendix.append(("Evidence: %s" % m.title, "\n\n".join(evid)[:60000]))
    return d


def build_fleet(runs, cfg, report_type="technical", errors=None):
    """Combined report for many servers (central/multi-server mode)."""
    d = ReportDoc()
    d.kind = "fleet"
    d.customer_logo = cfg.get("main", "general", "logo", "") if cfg else ""
    d.report_type = report_type
    d.title = (cfg.get("reports", "reports", "title", "") if cfg else "") or "Infrastructure Health Report"
    d.subtitle = "%d servers — fleet summary" % len(runs)
    meta = (runs[0].meta if runs else {}) or {}
    d.meta = [(k, v) for k, v in (("Company", meta.get("company")), ("Customer", meta.get("customer")),
                                   ("Servers", str(len(runs))), ("Generated", time.strftime("%Y-%m-%d %H:%M:%S")),
                                   ("Generated by", "%s v%s" % (APP_NAME, VERSION))) if v]
    worst = "HEALTHY"
    order = {"CRITICAL": 3, "WARNING": 2, "UNKNOWN": 1, "HEALTHY": 0}
    counts = {"CRITICAL": 0, "WARNING": 0, "UNKNOWN": 0, "INFO": 0}
    rows = []
    scores = []
    for r in sorted(runs, key=lambda x: (-order.get(x.health.get("status"), 0), x.health.get("score", 0))):
        h = r.health
        st = h.get("status", "UNKNOWN")
        if order.get(st, 0) > order[worst]:
            worst = st
        c = h.get("counts", {})
        for k in counts:
            counts[k] += c.get(k, 0)
        scores.append(h.get("score", 0))
        top = r.findings("WARNING")[:1]
        rows.append([r.fqdn or r.host, r.meta.get("group", ""), r.meta.get("environment", ""), h.get("score", ""), st,
                     c.get("CRITICAL", 0), c.get("WARNING", 0),
                     time.strftime("%Y-%m-%d %H:%M", time.localtime(r.collected_at)), redact(top[0].message)[:120] if top else ""])
        for f in r.findings("WARNING"):
            fd = f.to_dict()
            fd["component"] = "%s: %s" % (r.host, fd["component"])
            fd["evidence"] = redact(fd["evidence"])[:1000]
            d.findings.append(fd)
        d.charts["modules"].append((r.host, h.get("score", 0)))
    for host, err in (errors or {}).items():
        rows.append([host, "", "", "", "UNREACHABLE", "", "", "", err[:120]])
        d.findings.append({"severity": "CRITICAL", "code": "FLEET_COLLECTION_FAILED", "component": host,
                           "message": "Could not collect health data from %s" % host, "evidence": err[:1000],
                           "recommendation": "Check SSH connectivity/keys and that LSHME is installed on the server.", "module": "fleet"})
        counts["CRITICAL"] += 1
        worst = "CRITICAL"
    d.counts = counts
    d.health = {"score": int(round(sum(scores) / len(scores))) if scores else 0, "status": worst, "counts": counts}
    fleet_table = Table("Server overview", ["Server", "Group", "Environment", "Score", "Status", "Critical", "Warning", "Collected", "Top issue"],
                        rows, kind="summary")
    d.module_rows = [[r[0], r[3], r[4], r[5], r[6], r[8]] for r in rows]
    d.sections.append(Section("fleet", "Fleet overview", worst, d.health["score"], "%d servers" % len(rows), [], [fleet_table]))
    # module status matrix
    mods = []
    for r in runs:
        for m in r.modules:
            if m.title not in mods:
                mods.append(m.title)
    matrix = []
    for r in runs:
        row = [r.host]
        by = dict((m.title, m) for m in r.modules)
        for t in mods:
            m = by.get(t)
            row.append("-" if not m or m.score is None else ("%s %s" % (m.score, "!" * (2 if m.worst() == "CRITICAL" else 1 if m.worst() == "WARNING" else 0))).strip())
        matrix.append(row)
    if matrix:
        d.sections.append(Section("matrix", "Module scores by server", worst, None, "", [],
                                  [Table("Module score matrix (! warning, !! critical)", ["Server"] + mods, matrix, kind="summary")]))
    if report_type != "executive":
        for r in runs:
            sub = build(r, cfg, "executive")
            tables = [Table("%s — %s" % (r.host, t.title), t.headers, t.rows, t.note, "detail") for s in sub.sections for t in s.tables
                      if s.name in ("system", "storage", "database")]
            d.sections.append(Section("host:" + r.host, "Server %s" % r.host, r.health.get("status"), r.health.get("score"),
                                      "", [f for f in d.findings if f["component"].startswith(r.host + ":")], tables))
    d.findings.sort(key=lambda f: -SEV_RANK[f["severity"]])
    seen = set()
    for f in d.findings:
        if f.get("recommendation") and f["recommendation"] not in seen and SEV_RANK[f["severity"]] >= 2:
            seen.add(f["recommendation"])
            d.recommendations.append((f["severity"], f["component"], f["recommendation"]))
    return d
